enum CountdownMessageType {
  /// Holiday greetings on Christmas Day (Dec 25th)
  christmasDay,

  /// Message when under 24 hours remain
  under24Hours,

  /// Message when 1 to 7 days remain
  oneToSevenDays,

  /// Message when 8 to 30 days remain
  eightToThirtyDays,

  /// Message when over 30 days remain
  overThirtyDays,
}
